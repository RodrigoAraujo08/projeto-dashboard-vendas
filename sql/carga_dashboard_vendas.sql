CREATE VIEW vw_vendas_powerbi AS
SELECT v.venda_id, v.data_venda, c.cliente_id, c.nome_cliente AS cliente,
       c.cidade, c.estado, v.forma_pagamento, i.item_venda_id AS item_id,
       p.produto_id, p.nome_produto AS produto, cat.nome_categoria AS categoria,
       i.quantidade, i.preco_unitario, i.subtotal
FROM vendas v
JOIN clientes c ON c.cliente_id = v.cliente_id
JOIN itens_venda i ON i.venda_id = v.venda_id
JOIN produtos p ON p.produto_id = i.produto_id
JOIN categorias cat ON cat.categoria_id = p.categoria_id;
COMMIT;
SELECT 'categorias' AS tabela, count(*) AS linhas FROM categorias UNION ALL SELECT 'clientes', count(*) FROM clientes UNION ALL SELECT 'produtos', count(*) FROM produtos UNION ALL SELECT 'vendas', count(*) FROM vendas UNION ALL SELECT 'itens_venda', count(*) FROM itens_venda;
SELECT count(*) AS linhas_view, round(sum(subtotal),2) AS faturamento_itens FROM vw_vendas_powerbi;


